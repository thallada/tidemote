const SPAN = { Age: 'age', Years: 'years', Days: 'days', Time: 'time' };
const TIME = { Years: 'years', Days: 'days', Hours: 'hours' };
const NTH = { Second: 'second', Third: 'third', Fourth: 'fourth', Fifth: 'fifth', Sixth: 'sixth', Seventh: 'seventh', Eighth: 'eighth', Ninth: 'ninth' };

/** An era's name (climate.name, a history entry's, a card's home) as the page shows it. */
export function eraName(name) {
  if (name === FIRST_ERA) return tr('era.first', 'The First Tides');
  const e = parseEra(name);
  if (!e) return name; // (a name this version does not know: a key, not a message)
  const adj = ADJ[e.adj], noun = NOUN[e.noun], span = SPAN[e.span];
  switch (e.p) {
    case 'phrase': return PHRASE[e.phrase];
    // i18n: an era's name: "The Thaw" ({noun}: an era.noun word)
    case 'noun': return tr('era.name.noun', 'The {noun}', { noun });
    // i18n: an era's name: "The Long Thaw" ({adj}: an era.adj word, {noun}: an era.noun word)
    case 'adj-noun': return tr('era.name.adj-noun', 'The {adj} {noun}', { adj, noun });
    // i18n: an era's name when its kind of era comes again in a world: "The Second Thaw" ({noun}: an era.noun word)
    case 'ordinal': return tr('era.name.ordinal', 'The {nth, select, second {Second} third {Third} fourth {Fourth} fifth {Fifth} sixth {Sixth} seventh {Seventh} eighth {Eighth} other {Ninth}} {noun}', { nth: NTH[e.nth], noun });
    // i18n: an era's name: "Years of Thin Light" ({q}: an era.q word)
    case 'span': return tr('era.name.span', '{span, select, age {Age of {q}} years {Years of {q}} days {Days of {q}} other {Time of {q}}}', { span, q: Q[e.q] });
    // i18n: an era's name for who holds the pool: "Age of Pale Grazers" ({adj}: an era.adj word, {kin}: an era.kin word)
    case 'kin': return tr('era.name.kin', '{span, select, age {Age of {adj} {kin}} years {Years of {adj} {kin}} days {Days of {adj} {kin}} other {Time of {adj} {kin}}}', { span, adj, kin: KIN[Object.keys(KIN_EN).find((k) => KIN_EN[k] === e.kin)] });
    // i18n: an era's name: "The Lean Years" ({adj}: an era.adj word)
    case 'years': return tr('era.name.years', 'The {adj} {time, select, years {Years} days {Days} other {Hours}}', { adj, time: TIME[e.time] });
    // i18n: an era's name for one of the pool's events just past: "After the Rains" ({event}: an era.event word)
    case 'after': return tr('era.name.after', '{form, select, wake {In the Wake of the {event}} other {After the {event}}}', { form: e.form === 'After' ? 'after' : 'wake', event: EVENT[e.event] });
    // i18n: an era's name for a genus holding the pool: "The Quesku Ascendancy" ({genus}: its name; {noun}: an era.noun word)
    case 'genus': return tr('era.name.genus', 'The {genus} {noun}', { genus: e.genus, noun });
    // i18n: an era's name for a genus holding the pool: "Age of Quesku" ({genus}: its name)
    case 'genus-span': return tr('era.name.genus-span', '{span, select, age {Age of {genus}} years {Years of {genus}} days {Days of {genus}} other {Time of {genus}}}', { span, genus: e.genus });
    // i18n: an era's name coined like a stage of the rocks from a genus's name or the world's own ({coin}: "Queskian");
    // late: the next era of the same stage
    default: return tr('era.name.coin', '{stage, select, late {Late {coin}} other {The {coin}}}', { stage: e.stage === 'Late' ? 'late' : 'the', coin: e.coin });
  }
}
